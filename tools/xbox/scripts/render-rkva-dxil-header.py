#!/usr/bin/env python3
"""Render a compiled RKVA DXIL blob as an embedded C++ header.

This is the renderer used by scripts/compile-rkva-range-shaders.sh. It is kept
separate so an already-compiled blob (for example the offline GQA2 candidate)
can produce exactly the same header shape without invoking DXC.

The header records the target, the entry-source SHA256, every sibling the
wrapper includes, optional compiler flags and a non-default shader model. Those
provenance lines are the reason a prebuilt blob must be rendered through this
script rather than pasted into a header by hand.

Usage:
  render-rkva-dxil-header.py --binary candidate.dxil --output out.h \
      --source rkva_range_attn_kvarn4_mq_gqa2.hlsl \
      --target attn_kvarn4_mq2_gqa2
"""
import argparse
import hashlib
import pathlib


def render(binary, source, target, profile, compile_flags):
    data = pathlib.Path(binary).read_bytes()
    src_path = pathlib.Path(source)
    entry_text = src_path.read_text()
    # Record the hash of every sibling a wrapper includes: the entry-source hash
    # alone cannot tell a regenerated wrapper from a stale one when the included
    # kernel changes, which is exactly how a stale INT8 DXIL could ship.
    included = []
    for line in entry_text.splitlines():
        text = line.strip()
        if text.startswith('#include "') and text.endswith('.hlsl"'):
            name = text.split('"')[1]
            sibling = src_path.parent / name
            if sibling.exists():
                included.append('// Included "' + name + '" SHA256: ' +
                                hashlib.sha256(sibling.read_bytes()).hexdigest())
    lines = [
        '// Generated by scripts/compile-rkva-range-shaders.sh; do not edit.',
        '// Target specialization: ' + target,
        '// Source SHA256: ' + hashlib.sha256(src_path.read_bytes()).hexdigest(),
        *included,
        *(['// Rowlane include SHA256: ' + hashlib.sha256(
            src_path.with_name('rkva_decode_rowlane.hlsli').read_bytes()).hexdigest()]
          if target == 'attn_kvarn4_decode_rowlane' else []),
        *(['// Additional compiler options: ' + compile_flags] if compile_flags else []),
        *(['// Shader model: ' + profile] if profile != 'cs_6_0' else []),
        '#pragma once', '#include <cstdint>', '// clang-format off',
        'static const uint8_t g_rkva_range_' + target + '_dxil[] = {',
    ]
    for offset in range(0, len(data), 12):
        lines.append('    ' + ', '.join(f'0x{value:02x}' for value in data[offset:offset+12]) + ',')
    lines += ['};', '// clang-format on', '']
    return '\n'.join(lines), data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binary', required=True, help='compiled DXIL blob')
    parser.add_argument('--output', required=True, help='generated C++ header')
    parser.add_argument('--source', required=True, help='entry HLSL source or wrapper')
    parser.add_argument('--target', required=True, help='compile target name')
    parser.add_argument('--profile', default='cs_6_0', help='DXC target profile')
    parser.add_argument('--compile-flags', default='', help='extra DXC flags, for provenance')
    args = parser.parse_args()
    text, data = render(args.binary, args.source, args.target, args.profile,
                        args.compile_flags)
    pathlib.Path(args.output).write_text(text)
    print(args.output, len(data), 'bytes')


if __name__ == '__main__':
    main()
