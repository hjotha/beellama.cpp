"""Compile the D3D12 IQ-quant matmul kernels to checked-in DXIL headers.

Each kernel is built for the two group widths the backend selects with
d3d12_mm_threads(K): 64 and 128 threads. dxc can run locally (Windows build
host) or on a remote Windows host over SSH:

    python3 scripts/compile-iq-shaders.py
    python3 scripts/compile-iq-shaders.py --ssh-host hjotha@192.168.1.193 \
        --dxc "C:/Program Files (x86)/Windows Kits/10/bin/10.0.26100.0/x64/dxc.exe"

--check rebuilds and fails if a checked-in header differs from the compiler
output (same contract as compile-gpupeak-shaders.py --check).
"""

import argparse
import base64
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "shaders"
OUTPUT = ROOT / "shaders" / "generated"
REMOTE_DIR = "C:/Users/hjotha/build/rkva-shaders"

INCLUDES = ["ggml_d3d12_common.hlsli", "ggml_d3d12_iq_common.hlsli"]
KERNELS = [
    ("iq2_s", "ggml_d3d12_mmv_iq2_s.hlsl", "Iq2S"),
    ("iq3_xxs", "ggml_d3d12_mmv_iq3_xxs.hlsl", "Iq3Xxs"),
    ("iq3_s", "ggml_d3d12_mmv_iq3_s.hlsl", "Iq3S"),
    ("iq4_xs", "ggml_d3d12_mmv_iq4_xs.hlsl", "Iq4Xs"),
]
WIDTHS = (64, 128)


def compiler():
    explicit = os.environ.get("DXC")
    if explicit:
        return explicit
    found = shutil.which("dxc") or shutil.which("dxc.exe")
    if found:
        return found
    sdk = Path(r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\dxc.exe")
    if sdk.is_file():
        return str(sdk)
    raise SystemExit("dxc not found; set DXC to the compiler path")


def dxc_args(source, threads):
    return ["-T", "cs_6_0", "-E", "CSMain", "-O3", "-D", f"NUM_THREADS={threads}"]


def compile_local(dxc, source, threads, out, temp):
    cmd = [dxc] + dxc_args(source, threads) + ["-I", str(SOURCE), "-Fo", str(out), str(SOURCE / source)]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(result.stdout + result.stderr)


def compile_remote(host, dxc, source, threads, out, temp):
    # dxc resolves includes relative to the source file, so every header and
    # the kernel itself are copied into one remote scratch directory.
    for name in INCLUDES + [source]:
        subprocess.run(["scp", "-q", str(SOURCE / name), f"{host}:{REMOTE_DIR}/{name}"],
                       check=True)
    remote_out = REMOTE_DIR + "/" + out.name
    script = (
        "$ErrorActionPreference='Stop'; & "
        + quote(dxc) + " " + " ".join(quote(a) for a in dxc_args(source, threads))
        + " " + quote(f"{REMOTE_DIR}/{source}") + " -Fo " + quote(remote_out)
        + "; if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }"
    )
    encoded = base64.b64encode(script.encode("utf-16le")).decode()
    result = subprocess.run(["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=10", host,
                             "powershell -NoProfile -EncodedCommand " + encoded],
                            capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(result.stdout + result.stderr)
    subprocess.run(["scp", "-q", f"{host}:{remote_out}", str(out)], check=True)


def quote(value):
    return "'" + value.replace("'", "''") + "'"


def emit_header(path, source, threads, symbol, data):
    lines = [
        "// AUTO-GENERATED by scripts/compile-iq-shaders.py; do not edit.",
        f"// Source: shaders/{source} -D NUM_THREADS={threads} (cs_6_0 CSMain)",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        f"// {len(data)} bytes DXIL",
        "// clang-format off",
        f"static const uint8_t {symbol}[] = {{",
    ]
    for index in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[index:index + 12]) + ",")
    lines.extend(["};", f"static const size_t {symbol}Size = {len(data)};", "// clang-format on"])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ssh-host", default=None)
    parser.add_argument("--dxc", default=None)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    dxc = args.dxc or compiler()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as temporary:
        temp = Path(temporary)
        for _, source, stem in KERNELS:
            for threads in WIDTHS:
                out = temp / f"{Path(source).stem}_t{threads}.dxil"
                if args.ssh_host:
                    compile_remote(args.ssh_host, dxc, source, threads, out, temp)
                else:
                    compile_local(dxc, source, threads, out, temp)
                symbol = f"kGgmlD3d12Mmv{stem}T{threads}Dxil"
                header = OUTPUT / f"{Path(source).stem}_t{threads}_dxil.h"
                data = out.read_bytes()
                if args.check:
                    if not header.is_file():
                        raise SystemExit("missing: " + str(header))
                    current = header.read_text(encoding="utf-8")
                    marker = "// clang-format off"
                    if marker not in current:
                        raise SystemExit("stale: " + str(header))
                    with tempfile.TemporaryDirectory() as check_dir:
                        probe = Path(check_dir) / header.name
                        emit_header(probe, source, threads, symbol, data)
                        if probe.read_text(encoding="utf-8") != current:
                            raise SystemExit("stale: " + str(header))
                    print(f"ok: {header.name} ({len(data)} bytes)")
                else:
                    emit_header(header, source, threads, symbol, data)
                    print(f"{header.name}: {len(data)} bytes")


if __name__ == "__main__":
    main()
