"""Compile the dedicated DFlash K-quant kernels to checked-in DXIL headers."""

import os
import shutil
import subprocess
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "shaders" / "dflash"
OUTPUT = ROOT / "shaders" / "generated"


def compiler():
    explicit = os.environ.get("DXC")
    if explicit:
        return explicit
    found = shutil.which("dxc") or shutil.which("dxc.exe")
    if found:
        return found
    sdk = Path(r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\dxc.exe")
    if sdk.is_file():
        return str(sdk)
    raise SystemExit("dxc not found; set DXC to the compiler path")


def emit_header(path, source, symbol, data):
    lines = [
        "// AUTO-GENERATED by scripts/compile-dflash-shaders.py; do not edit.",
        f"// Source: shaders/dflash/{source} (cs_6_0 CSMain)",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        f"// {len(data)} bytes DXIL",
        "// clang-format off",
        f"static const uint8_t {symbol}[] = {{",
    ]
    for index in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[index:index + 12]) + ",")
    lines.extend(["};", f"static const size_t {symbol}Size = {len(data)};", "// clang-format on"])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    dxc = compiler()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for quant in (3, 5):
        source = f"q{quant}k_matmul.hlsl"
        for tile in (1, 2, 4, 8):
            name = f"dflash_q{quant}k_t{tile}_dxil.h"
            symbol = f"kDflashQ{quant}kT{tile}Dxil"
            with tempfile.TemporaryDirectory() as temporary:
                dxil = Path(temporary) / "kernel.dxil"
                subprocess.run([dxc, "-T", "cs_6_0", "-E", "CSMain", "-O3",
                                "-I", str(SOURCE), "-D", f"DFLASH_BATCH_TILE={tile}",
                                "-Fo", str(dxil), str(SOURCE / source)], check=True)
                data = dxil.read_bytes()
            emit_header(OUTPUT / name, source, symbol, data)
            print(f"{name}: {len(data)} bytes")


if __name__ == "__main__":
    main()
