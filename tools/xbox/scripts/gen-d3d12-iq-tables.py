"""Emit the D3D12 IQ-quant lookup tables as one checked-in C header.

The D3D12 matmul kernels for IQ2_S, IQ3_XXS, IQ3_S and IQ4_XS need the same
grids/codebooks as ggml's dequantizers. They live in one read-only buffer bound
as root SRV t1 (see ggml_d3d12_iq_common.hlsli), not in shader constant space:
the IQ2_S grid alone is 8 KiB and every lookup index is lane-divergent.

Layout (must match the *_BASE constants in ggml_d3d12_iq_common.hlsli):

    0      iq2s_grid     1024 x uint64   (little-endian, as the C table)
    8192   iq3xxs_grid    256 x uint32
    9216   iq3s_grid      512 x uint32
    11264  ksigns_iq2xs   128 x uint8
    11392  kvalues_iq4nl   16 x float32  (int8 table widened)

Usage:
    python3 scripts/gen-d3d12-iq-tables.py [--ggml-common PATH] [--check]

--check regenerates in memory and fails if the checked-in header differs.
"""

import argparse
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_COMMON = ROOT.parents[1] / "ggml" / "src" / "ggml-common.h"
OUTPUT = ROOT / "shaders" / "generated" / "ggml_d3d12_iq_tables.h"

IQ2S_GRID = 0
IQ3XXS_GRID = 8192
IQ3S_GRID = 9216
IQ_SIGNS = 11264
IQ4NL = 11392
TOTAL = 11456


def parse_table(source, name):
    pattern = r"GGML_TABLE_BEGIN\([^,]+,\s*" + name + r",\s*\d+\)(.*?)GGML_TABLE_END\(\)"
    match = re.search(pattern, source, re.S)
    if not match:
        raise SystemExit("table not found: " + name)
    body = match.group(1)
    values = [int(token, 0) for token in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", body)]
    return values


def pack(source):
    iq2s = parse_table(source, "iq2s_grid")
    iq3xxs = parse_table(source, "iq3xxs_grid")
    iq3s = parse_table(source, "iq3s_grid")
    signs = parse_table(source, "ksigns_iq2xs")
    iq4nl = parse_table(source, "kvalues_iq4nl")
    if len(iq2s) != 1024 or len(iq3xxs) != 256 or len(iq3s) != 512:
        raise SystemExit("unexpected grid sizes: %d %d %d" % (len(iq2s), len(iq3xxs), len(iq3s)))
    if len(signs) != 128 or len(iq4nl) != 16:
        raise SystemExit("unexpected table sizes: %d %d" % (len(signs), len(iq4nl)))

    blob = bytearray()
    for value in iq2s:
        blob += struct.pack("<Q", value)
    for value in iq3xxs:
        blob += struct.pack("<I", value)
    for value in iq3s:
        blob += struct.pack("<I", value)
    blob += bytes(signs)
    for value in iq4nl:
        blob += struct.pack("<f", float(value))
    if len(blob) != TOTAL:
        raise SystemExit("unexpected blob size: %d" % len(blob))
    return blob


def emit(blob):
    lines = [
        "// AUTO-GENERATED by scripts/gen-d3d12-iq-tables.py; do not edit.",
        "// Source: ggml/src/ggml-common.h (iq2s_grid, iq3xxs_grid, iq3s_grid,",
        "// ksigns_iq2xs, kvalues_iq4nl). Bound as root SRV t1 by the IQ matmul",
        "// kernels; offsets mirror the *_BASE constants in",
        "// shaders/ggml_d3d12_iq_common.hlsli.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "static const std::uint32_t kD3d12Iq2sGrid = %du;      // 1024 x uint64"
        % IQ2S_GRID,
        "static const std::uint32_t kD3d12Iq3xxsGrid = %du;    // 256 x uint32"
        % IQ3XXS_GRID,
        "static const std::uint32_t kD3d12Iq3sGrid = %du;      // 512 x uint32"
        % IQ3S_GRID,
        "static const std::uint32_t kD3d12IqSigns = %du;       // 128 x uint8"
        % IQ_SIGNS,
        "static const std::uint32_t kD3d12Iq4nl = %du;         // 16 x float32"
        % IQ4NL,
        "static const std::uint32_t kD3d12IqTableBytes = %du;" % TOTAL,
        "// clang-format off",
        "static const std::uint8_t kD3d12IqTable[%d] = {" % TOTAL,
    ]
    for index in range(0, len(blob), 12):
        lines.append("    " + ", ".join("0x%02x" % byte for byte in blob[index:index + 12]) + ",")
    lines.extend(["};", "// clang-format on"])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ggml-common", default=str(DEFAULT_COMMON))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = Path(args.ggml_common).read_text(encoding="utf-8")
    text = emit(pack(source))
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("stale: " + str(OUTPUT))
        print("ok: %s" % OUTPUT)
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print("%s: %d bytes" % (OUTPUT, TOTAL))


if __name__ == "__main__":
    main()
